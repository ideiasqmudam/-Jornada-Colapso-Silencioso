export function selecionarSilenciadores(fingerprintKey, respostas) {
  const lvl = { B: 0, M: 1, A: 2 };
  const [nM, nF, nC, nI] = fingerprintKey.split('').map(c => lvl[c]);
  const scores = { M: nM, F: nF, C: nC, I: nI };
  const dimMaisBaixa = Object.entries(scores).sort((a, b) => a[1] - b[1])[0][0];

  const r = {};
  (respostas || []).forEach(item => { r[item.perguntaId] = item.opcaoKey; });

  const lista = [];
  const add = (id) => { if (id && !lista.includes(id)) lista.push(id); };
  ORDEM_PERGUNTAS.forEach(q => { if (r[q] === 'D') add(RESPOSTA_HABITO[q]); });
  const gatilhos = lista.length + ORDEM_PERGUNTAS.filter(q => r[q] === 'C').length;
  ORDEM_PERGUNTAS.forEach(q => { if (r[q] === 'C') add(RESPOSTA_HABITO[q]); });
  add(TENTATIVA_HABITO[r[14]]);

  SILENCIADORES_POR_DIM[dimMaisBaixa].forEach(add);
  SILENCIADORES_POR_DIM.M.forEach(add);

  const alvo = gatilhos >= 3 ? 5 : 4;
  let final = lista.slice(0, alvo);
  if (!final.some(id => HABITOS_MEMORIA.includes(id))) {
    final = ['memoria-episodica', ...final].slice(0, alvo);
  }
  return final.map(id => (SILENCIADORES_POOL[id] ? { id, ...SILENCIADORES_POOL[id] } : null)).filter(Boolean);
}
